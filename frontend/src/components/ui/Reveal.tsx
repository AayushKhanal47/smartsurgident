import { motion, useReducedMotion } from "framer-motion";
import type { ReactNode } from "react";

// Generic scroll-reveal wrapper — used for cards, images, and content blocks
// that need the same fade+slide entrance without repeating the motion config
// everywhere. `delay` lets sibling items stagger visually.
export default function Reveal({
  children,
  delay = 0,
  className = "",
}: {
  children: ReactNode;
  delay?: number;
  className?: string;
}) {
  const reduceMotion = useReducedMotion();

  return (
    <motion.div
      initial={reduceMotion ? undefined : { opacity: 0, y: 20 }}
      whileInView={reduceMotion ? undefined : { opacity: 1, y: 0 }}
      viewport={{ once: true, margin: "-60px" }}
      transition={{ duration: 0.5, ease: "easeOut", delay }}
      className={className}
    >
      {children}
    </motion.div>
  );
}
